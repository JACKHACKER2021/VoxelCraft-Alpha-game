#!/usr/bin/env python3
"""2.8.0: packs the vanilla VC creature models (assets_src/models_vc/mobs/*.glb) into the engine
as app/src/main/cpp/engine/VcBuiltinModels.inc. The GLB is the source; the engine reads it (VcModel)."""
import os, sys
root = sys.argv[1] if len(sys.argv) > 1 else '.'
names = ['pig', 'sheep', 'chicken', 'cow', 'ghost']
out = ['// Generated by tools/glb_to_inc.py from assets_src/models_vc/mobs (tools/vc_reskin.py). Do not edit.']
for n in names:
    d = open(os.path.join(root, 'assets_src/models_vc/mobs', n + '.glb'), 'rb').read()
    out.append('static const unsigned char kGlb_%s[%d] = {' % (n, len(d)))
    for i in range(0, len(d), 32):
        out.append(','.join(str(b) for b in d[i:i + 32]) + ',')
    out.append('};')
out.append('struct BuiltinGlb { const char* id; const unsigned char* data; unsigned size; };')
out.append('static const BuiltinGlb kBuiltinGlbs[] = {' + ', '.join('{"%s", kGlb_%s, sizeof(kGlb_%s)}' % (n, n, n) for n in names) + '};')
open(os.path.join(root, 'app/src/main/cpp/engine/VcBuiltinModels.inc'), 'w').write('\n'.join(out) + '\n')
