#!/usr/bin/env python3
"""2.2.0 preview: the HUD buttons the project designed (assets_src/textures/hud_buttons/*_full.png,
cut from the design sheet) as 32x32 RGBA for engine/HudButtons.inc."""
import os, sys
from PIL import Image

SRC, OUT = sys.argv[1], sys.argv[2]
NAMES = ["up", "down", "left", "right", "jump", "sneak", "camera", "pause", "chat"]
with open(OUT, "w") as o:
    o.write("// Generated by tools/hud_buttons.py. Do not edit by hand.\n")
    o.write("// up, down, left, right, jump, sneak, camera, pause, chat: 32 x 32 RGBA each.\n")
    o.write("const uint8_t kHudButtons[9][32 * 32 * 4] = {\n")
    for n in NAMES:
        im = Image.open(os.path.join(SRC, n + "_full.png")).convert("RGBA")
        w, h = im.size
        im = im.crop((5, 5, w - 5, h - 5)).resize((32, 32), Image.LANCZOS)
        px = im.load()
        # The rounded corners: the dark background behind them becomes transparent.
        for (x, y) in [(0, 0), (1, 0), (0, 1), (31, 0), (30, 0), (31, 1), (0, 31), (1, 31), (0, 30), (31, 31), (30, 31), (31, 30)]:
            px[x, y] = (0, 0, 0, 0)
        o.write("    {%s},\n" % ",".join(str(b) for b in im.tobytes()))
    o.write("};\n")
