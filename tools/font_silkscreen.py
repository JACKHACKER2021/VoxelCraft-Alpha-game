#!/usr/bin/env python3
"""2.2.0 preview: turns the "Tiny Caps" glyph sheet (Silkscreen, SIL Open Font License 1.1, from
the pack the project made: assets_src/fonts/silkscreen) into engine/FontSilkscreen.inc: 8 rows
of 8 pixels for each ASCII character 32..126 (bit 0 = left pixel)."""
import sys
from PIL import Image

src, out = sys.argv[1], sys.argv[2]
im = Image.open(src).convert("RGBA")
with open(out, "w") as o:
    o.write("// Generated by tools/font_silkscreen.py from assets_src/fonts/silkscreen/default8.png.\n")
    o.write("// Silkscreen, Copyright 2001 The Silkscreen Project Authors, SIL Open Font License 1.1\n")
    o.write("// (assets_src/fonts/silkscreen/OFL-Silkscreen.txt). Do not edit by hand.\n")
    o.write("const uint8_t kSilkscreen[95][8] = {\n")
    for c in range(32, 127):
        x0, y0 = (c % 16) * 8, (c // 16) * 8
        rows = []
        for y in range(8):
            v = 0
            for x in range(8):
                if im.getpixel((x0 + x, y0 + y))[3] > 127:
                    v |= 1 << x
            rows.append(v)
        o.write("    {%s},  // %r\n" % (", ".join("0x%02X" % r for r in rows), chr(c)))
    o.write("};\n")
