#!/usr/bin/env python3
"""2.2.0 preview: the Cornerstone remaster textures (assets_src/textures/cornerstone_remaster/*_16.png,
our own pixel art) as RGBA arrays for engine/CornerstoneRemaster.inc."""
import os, sys
from PIL import Image

SRC, OUT = sys.argv[1], sys.argv[2]
TILES = [("netherrack", "T_NETHERRACK"), ("powerstone_ore", "T_POWERSTONE_ORE"), ("nether_grass_top", "T_NETHER_GRASS_TOP"),
         ("nether_grass_side", "T_NETHER_GRASS_SIDE"), ("nether_sprouts", "T_NETHER_SPROUTS"),
         ("wasteland_grass_top", "T_WASTELAND_GRASS_TOP"), ("wasteland_grass_side", "T_WASTELAND_GRASS_SIDE"),
         ("cornerstone_bricks", "T_NETHER_BRICK"), ("cracked_cornerstone_bricks", "T_CRACKED_NETHER_BRICKS"),
         ("chiseled_cornerstone_bricks_side", "T_CHISELED_NETHER_BRICKS"),
         # 2.2.0: the project's own designs for the new biomes' blocks
         ("mossy_cornerstone", "T_MOSSY_CORNERSTONE"), ("luminous_salt", "T_LUMINOUS_SALT"), ("gilded_cobble", "T_GILDED_COBBLE"),
         ("amber_resin", "T_AMBER_RESIN"), ("carved_cornerstone", "T_CARVED_CORNERSTONE"), ("aether_brine", "T_AETHER_BRINE"),
         ("glass_reeds", "T_GLASS_REEDS"), ("copper_moss", "T_COPPER_MOSS"), ("spore_pad_top", "T_SPORE_PAD_TOP"),
         ("spore_pad_side", "T_SPORE_PAD_SIDE"), ("stonewood_log", "T_STONEWOOD_LOG"), ("stonewood_top", "T_STONEWOOD_TOP"),
         ("starberry_bush", "T_STARBERRY_BUSH"), ("glowcap_leaves", "T_GLOWCAP_LEAVES"), ("starberries", "T_STARBERRIES"), ("siltstone", "T_SILTSTONE")]
ALPHA = {"amber_resin": 210, "aether_brine": 200}  # see-through blocks
with open(OUT, "w") as o:
    o.write("// Generated by tools/cornerstone_remaster.py. Do not edit by hand.\n")
    o.write("struct RemasterTile { int tile; uint8_t rgba[16 * 16 * 4]; };\n")
    o.write("const RemasterTile kCornerstoneRemaster[] = {\n")
    for name, tile in TILES:
        im = Image.open(os.path.join(SRC, name + "_16.png")).convert("RGBA")
        if name in ALPHA:
            px = im.load()
            for y in range(16):
                for x in range(16):
                    px[x, y] = px[x, y][:3] + (ALPHA[name],)
        data = im.tobytes()
        o.write("    {%s, {%s}},\n" % (tile, ",".join(str(b) for b in data)))
    o.write("};\n")
